import re
import os
import sys

def parse_dbc(file_path):
    messages = []
    current_msg = None
    
    msg_regex = re.compile(r"^BO_\s+(\d+)\s+(\w+)\s*:\s*(\d+)\s+(\w+)")
    sig_regex = re.compile(r"^\s*SG_\s+(\w+)\s*:\s*(\d+)\|(\d+)@([01])([+-])\s+\(([\d.-]+),([\d.-]+)\)\s+\[([\d.-]+)\|([\d.-]+)\]\s+\"([^\"]*)\"\s+(\w+)")

    with open(file_path, "r") as f:
        for line in f:
            line = line.strip()
            msg_match = msg_regex.match(line)
            if msg_match:
                msg_id = int(msg_match.group(1))
                msg_name = msg_match.group(2)
                dlc = int(msg_match.group(3))
                sender = msg_match.group(4)
                current_msg = {
                    "id": msg_id,
                    "name": msg_name,
                    "dlc": dlc,
                    "sender": sender,
                    "signals": []
                }
                messages.append(current_msg)
                continue

            sig_match = sig_regex.match(line)
            if sig_match and current_msg:
                signal = {
                    "name": sig_match.group(1),
                    "start_bit": int(sig_match.group(2)),
                    "length": int(sig_match.group(3)),
                    "is_intel": sig_match.group(4) == '1',
                    "is_signed": sig_match.group(5) == '-',
                    "factor": float(sig_match.group(6)),
                    "offset": float(sig_match.group(7)),
                    "min": float(sig_match.group(8)),
                    "max": float(sig_match.group(9)),
                    "unit": sig_match.group(10),
                    "receiver": sig_match.group(11)
                }
                current_msg["signals"].append(signal)

    return messages

def generate_c_code(messages, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    h_path = os.path.join(out_dir, "Can_Com_Generated.h")
    c_path = os.path.join(out_dir, "Can_Com_Generated.c")

    with open(h_path, "w") as h:
        h.write("/* Auto-generated by dbc_to_autosar.py - DO NOT EDIT MANUALLY */\n")
        h.write("#ifndef CAN_COM_GENERATED_H\n#define CAN_COM_GENERATED_H\n\n")
        h.write("#include <stdint.h>\n#include <string.h>\n#include <stdbool.h>\n\n")

        for msg in messages:
            h.write(f"/* Message: {msg['name']} (ID: 0x{msg['id']:03X}, DLC: {msg['dlc']}) */\n")
            h.write(f"#define {msg['name'].upper()}_CAN_ID   (0x{msg['id']:03X}U)\n")
            h.write(f"#define {msg['name'].upper()}_DATA_LEN (8U)\n\n")
            
            h.write(f"typedef struct {{\n")
            for sig in msg["signals"]:
                h.write(f"    float {sig['name']}; /* Unit: {sig['unit']} [{sig['min']} to {sig['max']}] */\n")
            h.write(f"}} {msg['name']}_PhysType;\n\n")

            h.write(f"void {msg['name']}_Pack(const {msg['name']}_PhysType* phys, uint8_t* pdu_data);\n")
            h.write(f"void {msg['name']}_Unpack(const uint8_t* pdu_data, {msg['name']}_PhysType* phys);\n\n")

        h.write("#endif /* CAN_COM_GENERATED_H */\n")

    with open(c_path, "w") as c:
        c.write("/* Auto-generated by dbc_to_autosar.py - DO NOT EDIT MANUALLY */\n")
        c.write("#include \"Can_Com_Generated.h\"\n\n")

        for msg in messages:
            c.write(f"void {msg['name']}_Pack(const {msg['name']}_PhysType* phys, uint8_t* pdu_data)\n{{\n")
            c.write(f"    if (!phys || !pdu_data) return;\n")
            c.write(f"    uint64_t raw_frame = 0ULL;\n\n")
            
            for sig in msg["signals"]:
                c.write(f"    /* Signal: {sig['name']} */\n")
                c.write(f"    float {sig['name']}_phys = phys->{sig['name']};\n")
                c.write(f"    if ({sig['name']}_phys < {sig['min']}f) {sig['name']}_phys = {sig['min']}f;\n")
                c.write(f"    if ({sig['name']}_phys > {sig['max']}f) {sig['name']}_phys = {sig['max']}f;\n")
                c.write(f"    uint64_t {sig['name']}_raw = (uint64_t)(({sig['name']}_phys - ({sig['offset']}f)) / ({sig['factor']}f) + 0.5f);\n")
                mask = (1 << sig['length']) - 1
                c.write(f"    {sig['name']}_raw &= 0x{mask:X}ULL;\n")
                c.write(f"    raw_frame |= ({sig['name']}_raw << {sig['start_bit']}U);\n\n")

            c.write(f"    for (int i = 0; i < 8; i++) {{\n")
            c.write(f"        pdu_data[i] = (uint8_t)((raw_frame >> (i * 8)) & 0xFFU);\n")
            c.write(f"    }}\n")
            c.write(f"}}\n\n")

            c.write(f"void {msg['name']}_Unpack(const uint8_t* pdu_data, {msg['name']}_PhysType* phys)\n{{\n")
            c.write(f"    if (!phys || !pdu_data) return;\n")
            c.write(f"    uint64_t raw_frame = 0ULL;\n\n")
            c.write(f"    for (int i = 0; i < 8; i++) {{\n")
            c.write(f"        raw_frame |= ((uint64_t)pdu_data[i]) << (i * 8);\n")
            c.write(f"    }}\n\n")

            for sig in msg["signals"]:
                mask = (1 << sig['length']) - 1
                c.write(f"    /* Signal: {sig['name']} */\n")
                c.write(f"    uint64_t {sig['name']}_raw = (raw_frame >> {sig['start_bit']}U) & 0x{mask:X}ULL;\n")
                c.write(f"    phys->{sig['name']} = ((float){sig['name']}_raw * {sig['factor']}f) + ({sig['offset']}f);\n")

            c.write(f"}}\n\n")

    print("[SUCCESS] Automated code generation finished:")
    print(f"  -> Generated: {h_path}")
    print(f"  -> Generated: {c_path}")

if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Usage: python dbc_to_autosar.py <input.dbc> <output_dir>")
        sys.exit(1)
    
    parsed = parse_dbc(sys.argv[1])
    generate_c_code(parsed, sys.argv[2])